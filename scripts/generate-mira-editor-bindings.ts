/** Freeze the settings page's existing display associations against the committed CFG keys.
 * Runtime editing must never match fields by their position in an imported file.
 * Run: npx tsx scripts/generate-mira-editor-bindings.ts
 * Review the generated diff whenever the reference config or registries change.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { MiraModifiers, MiraRoles, MiraSettings } from '../src/mira';
import { normalizeLookupKey, parseCfgSections, stripConfigAffixes } from '../src/app/dramaafera/_utils/miraConfig';

const bindings: Record<string, Record<string, number>> = {};
for (const section of parseCfgSections(readFileSync('public/settings/mira.cfg', 'utf8'))) {
    if (section.name.split('.').some(part => part === 'HideAndSeek' || /^Hns/.test(part))) continue;
    const token = stripConfigAffixes(section.name.split('.').at(-1) ?? '');
    const groupToken = normalizeLookupKey((section.name.split('.').at(-1) ?? '').replace(/Options$/i, ''));
    const group = section.name.includes('.Roles.')
        ? MiraRoles.find(entry => normalizeLookupKey(entry.name) === normalizeLookupKey(token))
        : section.name.includes('.Modifiers.')
        ? MiraModifiers.find(entry => normalizeLookupKey(entry.name) === normalizeLookupKey(token))
        : MiraSettings.find(entry => normalizeLookupKey(entry.cfgKey) === groupToken);
    if (!group) continue;
    const labels = Object.keys(group.settings).filter(label => label !== 'Probability Of Appearing');
    // Match the changelog's registry order against the reference preset, never an imported file.
    // Store positions so labels edited in src/mira are read live instead of copied here.
    bindings[section.name] = Object.fromEntries(section.entries.slice(0, labels.length).map((entry, index) => [entry.key, index]));
}
const sections = Object.entries(bindings).map(([section, fields]) =>
    `    ${JSON.stringify(section)}: ${JSON.stringify(fields)},`).join('\n');
writeFileSync('src/app/dramaafera/host/_utils/settingBindings.ts',
    '// GENERATED by scripts/generate-mira-editor-bindings.ts; review before updating.\n' +
    '// Exact keys anchored to public/settings/mira.cfg, never the imported entry order.\n' +
    `export const SETTING_BINDINGS: Readonly<Record<string, Readonly<Record<string, number>>>> = {\n${sections}\n};\n`);
console.log(`Generated bindings for ${Object.keys(bindings).length} sections`);
